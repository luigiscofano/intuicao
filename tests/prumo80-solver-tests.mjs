import assert from 'node:assert/strict';
import {solveGeometry,validateGeometry,geometryCandidates,supportCells,geometryLocalAnalysis} from '../dist/geometry-games.mjs';
const l={game:'prumo',rows:10,cols:10,supports:Array.from({length:10},(_,s)=>({id:s,x2:9,y2:2*s}))};
const solution=Array.from({length:100},(_,i)=>Math.floor(i/10));
const started=performance.now();
for(let i=0;i<1000;i++)assert.equal(validateGeometry(l,solution).complete,true);
const validationMs=(performance.now()-started)/1000;
assert.ok(validationMs<25);
assert.equal(solveGeometry(l,solution).exhaustive,true);
assert.equal(solveGeometry(l,solution).count,1);
const result=solveGeometry(l,undefined,2,{maxSubsets:1,maxJoins:1,timeBudgetMs:1});
assert.equal(result.exhaustive,false);assert.equal(result.budgetExhausted,true);
const bad=solution.slice();bad[0]=1;assert.equal(validateGeometry(l,bad).complete,false);
assert.deepEqual(supportCells(l,{x2:1,y2:1}),[]);
assert.deepEqual(supportCells(l,{x2:9,y2:4}),[24,25]);
const incomplete=Array(100).fill(-1);incomplete[0]=5;
const check=validateGeometry(l,incomplete);assert.equal(check.valid,true);assert.equal(check.complete,false);assert.ok(check.pending.some(p=>p.code==='balance'));
const thin={game:'prumo',rows:10,cols:10,supports:Array.from({length:100},(_,s)=>({id:s,x2:2*(s%10),y2:2*Math.floor(s/10)}))};
const exact=solveGeometry(thin);assert.equal(exact.count,1);assert.equal(exact.exhaustive,true);
const aliased=solveGeometry({...l,supports:l.supports.map(p=>({...p,id:p.id+100}))},undefined,2,{maxOperations:1,maxMs:1});assert.equal(aliased.exhaustive,false);assert.equal(aliased.budgetExhausted,true);
const candidates=geometryCandidates(l);assert.equal(candidates.budgetExhausted,true);assert.equal(candidates.proof,'local-rule-propagation');assert.ok(candidates.candidates.every((choices,c)=>choices.includes(solution[c])),'budget fallback must retain every certified solution assignment');
console.log(JSON.stringify({pass:true,dimensions:'10x10',validationMs,completedIterations:1000,inconclusiveBudget:result.budgetExhausted,exactSingletonPartition:exact.count}));
