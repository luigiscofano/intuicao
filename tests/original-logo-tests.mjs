import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {restoreOriginalLogoHTML} from './original-logo-history.mjs';
const m=JSON.parse(fs.readFileSync(new URL('./original-logo-authorized-change.json',import.meta.url),'utf8'));
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const html=read('dist/index.html').toString(),css=read('dist/logo.css').toString();
assert.equal(sha(html),m.afterHtmlSHA256,'Current document matches exact approved logo changes');
assert.equal(sha(restoreOriginalLogoHTML(html)),m.priorHtmlSHA256);
for(const [p,hash] of Object.entries({...m.preservedDistSHA256,...m.newFilesSHA256}))assert.equal(sha(read(p)),hash,'Protected file: '+p);
const png=read('dist/platform-assets/intuicao-logo-original.png');
assert.equal(sha(png),m.originalPngSHA256,'Supplied PNG is copied without pixel modification');
assert.equal(png.readUInt32BE(16),2048);assert.equal(png.readUInt32BE(20),682);assert.equal(png[25],6,'RGBA PNG retains transparency');
assert.equal((html.match(/class="brand-image"/g)||[]).length,2);
assert.equal((html.match(/alt="Intuição"/g)||[]).length,2);
assert.doesNotMatch(html,/class="brand-icon"|class="brand-dot"/);
assert.match(css,/height:auto/);assert.match(css,/overflow:visible/);
assert.doesNotMatch(css,/filter\s*:|clip-path\s*:|object-fit\s*:\s*cover/);
assert.match(css,/@media\(max-width:760px\)/);assert.match(css,/@media\(max-width:370px\)/);
assert.ok(html.includes('aria-label="Intuição, início"'));
console.log('PASS two original PNG logos, exact original bytes/proportions/transparency, scoped responsive CSS, preserved complete prior dist and historical HTML. Browser visual QA remains separate.');
