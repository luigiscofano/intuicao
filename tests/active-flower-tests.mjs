import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {restoreActiveFlowerCSS} from './active-flower-history.mjs';
import {restoreCompletedGreenCSS} from './completed-green-history.mjs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const m=JSON.parse(read('tests/active-flower-authorized-change.json'));
const green=JSON.parse(read('tests/completed-green-authorized-change.json'));
const css=read('dist/platform.css'),old=restoreActiveFlowerCSS(css);
assert.equal(sha(css),m.afterCssSHA256);
assert.equal(sha(old),m.priorCssSHA256);
assert.equal(m.priorCssSHA256,green.afterCssSHA256);
assert.equal(sha(restoreCompletedGreenCSS(css)),green.priorCssSHA256);
assert.equal(restoreActiveFlowerCSS(old),old);
assert.equal(m.replacements.length,1);
const {before,after}=m.replacements[0];
const selector=':where(body:not(:has(.lab:not([hidden]), #collection:not([hidden]) > .collection-lab))) #main > .games > button[aria-pressed=true]::after';
assert.equal(before.split('{')[0],selector);
assert.equal(after.split('{')[0],selector);
assert.equal(old.split(before).length-1,1);
assert.equal(css.split(after).length-1,1);
assert.equal(old.replace(before,after),css,'Only active menu marker changes: dimensions, typography, state and all other CSS identical');
assert.ok(before.includes('top:17px;right:14px;width:5px;height:5px;border-radius:50%;background:#ddd3a6'));
assert.ok(!css.includes(before),'Former gold dot is removed');
assert.ok(after.includes('content:"";position:absolute;top:-10px;right:14px;width:24px;height:24px'));
assert.ok(after.includes('background:url("platform-assets/active-flower.svg") center/contain no-repeat'));
assert.ok(after.includes('pointer-events:none;user-select:none'),'Decoration cannot intercept clicks or selection');
assert.ok(!/padding|margin|display|font|transform|animation|overflow/.test(after.slice(after.indexOf('{'))),'No flow or animation changes');
const asset=read('dist/'+m.asset);
assert.equal(sha(asset),m.assetSHA256);
assert.ok(asset.includes('viewBox="0 0 32 32"'));
assert.ok(asset.includes('fill="#b5c99d"')&&asset.includes('stroke="#617b50"'));
assert.ok(!/<script|<foreignObject|\bon\w+=|href=|url\(/i.test(asset),'Self-contained passive SVG');
for(const [file,hash] of Object.entries(m.preservedSourcesSHA256))assert.equal(sha(read('dist/'+file)),hash,'Navigation, ARIA, layout and game sources preserved: '+file);
assert.ok(read('dist/game-info.mjs').includes('card.offsetTop+card.offsetHeight/2-16'));
assert.ok(read('dist/game-info.css').includes('width:32px;height:32px'));
// Geometry invariant for the minimum observed 64px menu card and taller responsive cards.
// Flower bottom is 14px from the padding-box top; centered info button begins at >=16px.
const flowerTop=-10,flowerHeight=24,flowerBottom=flowerTop+flowerHeight;
for(const cardHeight of [64,72,80,96,112,160])assert.ok(flowerBottom<cardHeight/2-16,'Flower stays above the centered info control');
assert.ok(css.includes('#main > .games{gap:12px;'));
assert.ok(12>Math.abs(flowerTop),'10px protrusion fits the 12px row gap');
for(const invalid of [css+' ',old+' ',css+'\n'+after,css.replace('top:-10px;right:14px;width:24px','top:-9px;right:14px;width:24px')])assert.throws(()=>restoreActiveFlowerCSS(invalid),'Historical guard fails closed on tampering');
console.log('PASS active flower: one exact menu-only active-marker replacement, passive green SVG, no flow/state/ARIA/source changes, bounded non-overlap for cards >=64px, and historical chain fail-closed.');
