import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {restoreWhiteFlowerCSS} from './white-flower-history.mjs';
import {restoreReferenceFlowersCSS} from './reference-flowers-history.mjs';
import {restoreStemlessFlowerCSS} from './stemless-flower-history.mjs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const m=JSON.parse(read('tests/white-flower-authorized-change.json'));
const reference=JSON.parse(read('tests/reference-flowers-authorized-change.json'));
const current=read('dist/platform.css').toString(),css=restoreStemlessFlowerCSS(current),old=restoreWhiteFlowerCSS(css);
assert.equal(sha(css),m.afterCssSHA256,'Only the exact separately authorized stem mask is normalized');
assert.equal(restoreWhiteFlowerCSS(current),old,'Current stemless flower still restores the exact white-flower baseline');
assert.equal(sha(old),reference.afterCssSHA256,'Reference-flower authorization is not rebased');
assert.equal(restoreWhiteFlowerCSS(old),old);
assert.equal(sha(restoreReferenceFlowersCSS(current)),reference.priorCssSHA256,'Historical chain still restores exact earlier bytes');
assert.equal(m.replacements.length,1);assert.equal(m.removals.length,1);
const {before,after}=m.replacements[0],removal=m.removals[0];
assert.equal(old.replace(before,after).replace(removal.text,''),css,'Only two exact authorized CSS edits');
assert.equal(before.split('{')[0],after.split('{')[0],'Active selector unchanged');
assert.match(after,/^:where\(body:not\(:has\(\.lab:not\(\[hidden\]\), #collection:not\(\[hidden\]\) > \.collection-lab\)\)\) #main > \.games > button\[aria-pressed=true\]::after\{/,'Only active selection-card pseudo-element, never game contents');
const contour='filter:drop-shadow(.5px 0 0 #617b50) drop-shadow(-.5px 0 0 #617b50) drop-shadow(0 .5px 0 #617b50) drop-shadow(0 -.5px 0 #617b50);';
assert.equal(after.replace('flower-white-original.png','flower-green-original.png').replace(contour,''),before,'Position, 32px dimensions and every other property unchanged');
assert.match(after,/top:-13px;right:10px;width:32px;height:32px/);
assert.match(after,/pointer-events:none;user-select:none/);
assert.match(after,/box-shadow:none;/,'No rectangular box outline');
assert.equal(after.split(contour).length-1,1,'Four half-pixel alpha shadows, all zero blur, approved green only');
assert.match(removal.text,/button\[aria-pressed=true\]::before\{/);
assert.match(removal.text,/bottom:2px;right:44px;width:22px;height:22px/);
assert.ok(!css.includes(removal.text));
assert.doesNotMatch(css,/button\[aria-pressed=true\]::before\{[^}]*flower-white/,'Lower white duplicate removed');
const withoutActive=s=>s.replace(s===css?after:before,'').replace(removal.text,'');
assert.equal(withoutActive(css),withoutActive(old),'Other flowers, game styling, layout and decoration preserved byte-for-byte');
const filterRules=s=>[...s.matchAll(/([^{}]+)\{([^{}]*)\}/g)].filter(([,selector,body])=>/\bfilter\s*:/.test(body)).map(([rule])=>rule);
assert.deepEqual(filterRules(css.replace(after,'')),filterRules(old.replace(before,'')),'No added filter on any game root, ancestor or other decoration');
for(const asset of m.assets){
 const b=read('dist/'+asset.file);assert.equal(sha(b),asset.sha256);assert.equal(asset.sha256,asset.referenceSHA256,'Both originals remain byte-exact');
 assert.equal(b.subarray(0,8).toString('hex'),'89504e470d0a1a0a');assert.equal(b[25],6,'Original RGBA alpha retained');
 assert.deepEqual(asset,reference.assets.find(a=>a.file===asset.file));
}
for(const invalid of [css+' ',old+' ',css+after,css.replace(contour,contour.replace('.5px 0 0','.5px 0 1px')),css.replace(after,after.replace('pointer-events:none','pointer-events:auto')),css.replace('width:32px;height:32px','width:33px;height:32px'),css+removal.text])assert.throws(()=>restoreWhiteFlowerCSS(invalid),'Unauthorized changes fail closed');
console.log('PASS active original white flower, exact replacement/removal, fine green alpha contour with zero blur, passive 32px geometry, unchanged other flowers/assets and strict historical chain. Static contracts, not pixel QA.');
